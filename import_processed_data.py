
import sqlite3
import pandas as pd
from pathlib import Path

PROJECT = Path.cwd()
DATA = PROJECT / "data" / "processed"
DB = PROJECT / "bluestock_mf.db"

# Read CSV files
funds = pd.read_csv(
    DATA / "fund_master.csv",
    dtype={"amfi_code": "string"}
)

aum = pd.read_csv(DATA / "aum_by_fund_house.csv")

nav = pd.read_csv(
    DATA / "nav_history.csv",
    dtype={"amfi_code": "string"}
)

performance = pd.read_csv(
    DATA / "scheme_performance.csv",
    dtype={"amfi_code": "string"}
)

transactions = pd.read_csv(
    DATA / "investor_transactions.csv",
    dtype={"amfi_code": "string"}
)

# Parse dates safely. Invalid dates will stop the import.
date_columns = [
    (aum, "date", "aum_by_fund_house.csv"),
    (nav, "date", "nav_history.csv"),
    (transactions, "transaction_date", "investor_transactions.csv"),
]

all_dates = []
for df, col, filename in date_columns:
    parsed = pd.to_datetime(df[col], errors="coerce")
    invalid = parsed.isna()

    if invalid.any():
        print(f"\nInvalid dates in {filename}: {invalid.sum()}")
        print(df.loc[invalid, col].head(10).to_list())
        raise ValueError(
            f"Fix the invalid dates in {filename} before importing."
        )

    df[col] = parsed.dt.strftime("%Y-%m-%d")
    all_dates.extend(df[col].tolist())

# Include launch dates in the date dimension when valid
launch_dates = pd.to_datetime(funds["launch_date"], errors="coerce")
all_dates.extend(launch_dates.dropna().dt.strftime("%Y-%m-%d").tolist())

# Create one unique date record per date
unique_dates = sorted(set(all_dates))
date_dim = pd.DataFrame({"full_date": unique_dates})
date_dim["year"] = pd.to_datetime(date_dim["full_date"]).dt.year
date_dim["month"] = pd.to_datetime(date_dim["full_date"]).dt.month
date_dim["day"] = pd.to_datetime(date_dim["full_date"]).dt.day

with sqlite3.connect(DB) as conn:
    # Safety check: do not append duplicates on a rerun
    counts = {
        table: conn.execute(
            f'SELECT COUNT(*) FROM "{table}"'
        ).fetchone()[0]
        for table in [
            "dim_date", "dim_fund", "fact_aum",
            "fact_nav", "fact_performance", "fact_transactions"
        ]
    }

    if any(counts.values()):
        raise RuntimeError(
            "At least one target table already contains rows. "
            "Import stopped to avoid duplicates. Inspect the database first."
        )

    # Load funds. fund_key should be generated by the database.
    fund_columns = [
        "amfi_code", "scheme_name", "fund_house", "category",
        "sub_category", "plan", "launch_date", "benchmark",
        "expense_ratio_pct", "exit_load_pct", "min_sip_amount",
        "min_lumpsum_amount", "fund_manager", "risk_category",
        "sebi_category_code"
    ]
    funds[fund_columns].to_sql(
        "dim_fund", conn, if_exists="append", index=False
    )

    # Build lookup dictionaries from the database-generated keys
    funds["amfi_code"] = funds["amfi_code"].str.strip()
    nav["amfi_code"] = nav["amfi_code"].str.strip()
    performance["amfi_code"] = performance["amfi_code"].str.strip()
    transactions["amfi_code"] = transactions["amfi_code"].str.strip()
    fund_map = dict(conn.execute(
        "SELECT amfi_code, fund_key FROM dim_fund"
    ).fetchall())
    print("Fund master AMFI code type:", funds["amfi_code"].dtype)
    print("NAV AMFI code type:", nav["amfi_code"].dtype)
    print("Sample fund_map codes:", list(fund_map.keys())[:5])
    print("Sample NAV codes:", nav["amfi_code"].head().tolist())

    # Insert dates and retrieve generated date keys
    date_dim.to_sql("dim_date", conn, if_exists="append", index=False)

    date_map = dict(conn.execute(
        "SELECT full_date, date_key FROM dim_date"
    ).fetchall())

    # AUM
    aum["date_key"] = aum["date"].map(date_map)
    aum_columns = [
        "date_key", "fund_house", "aum_lakh_crore",
        "aum_crore", "num_schemes"
    ]
    aum[aum_columns].to_sql(
        "fact_aum", conn, if_exists="append", index=False
    )

    # NAV
    nav["fund_key"] = nav["amfi_code"].map(fund_map)
    nav["date_key"] = nav["date"].map(date_map)

    # Stop if a NAV scheme has no corresponding fund
    if nav["fund_key"].isna().any():
        missing = nav.loc[nav["fund_key"].isna(), "amfi_code"].unique()
        raise ValueError(f"NAV has unknown AMFI codes: {missing[:10]}")

    nav[["fund_key", "date_key", "nav"]].to_sql(
        "fact_nav", conn, if_exists="append", index=False
    )

    # Scheme performance
    performance["fund_key"] = performance["amfi_code"].map(fund_map)

    if performance["fund_key"].isna().any():
        missing = performance.loc[
            performance["fund_key"].isna(), "amfi_code"
        ].unique()
        raise ValueError(
            f"Performance has unknown AMFI codes: {missing[:10]}"
        )

    performance_columns = [
        "fund_key", "return_1yr_pct", "return_3yr_pct",
        "return_5yr_pct", "benchmark_3yr_pct", "alpha", "beta",
        "sharpe_ratio", "sortino_ratio", "std_dev_ann_pct",
        "max_drawdown_pct", "aum_crore"
    ]
    performance[performance_columns].to_sql(
        "fact_performance", conn, if_exists="append", index=False
    )

    # Investor transactions
    transactions["fund_key"] = transactions["amfi_code"].map(fund_map)
    transactions["date_key"] = transactions["transaction_date"].map(date_map)

    if transactions["fund_key"].isna().any():
        missing = transactions.loc[
            transactions["fund_key"].isna(), "amfi_code"
        ].unique()
        raise ValueError(
            f"Transactions have unknown AMFI codes: {missing[:10]}"
        )

    transaction_columns = [
        "investor_id", "fund_key", "date_key", "transaction_type",
        "amount_inr", "state", "city", "city_tier", "age_group",
        "gender", "annual_income_lakh", "payment_mode", "kyc_status"
    ]
    transactions[transaction_columns].to_sql(
        "fact_transactions", conn, if_exists="append", index=False
    )

    print("Import completed.")
    print("\nFinal table row counts:")
    for table in counts:
        count = conn.execute(
            f'SELECT COUNT(*) FROM "{table}"'
        ).fetchone()[0]
        print(f"{table}: {count}")
